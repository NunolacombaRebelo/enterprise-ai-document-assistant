"""Local development persistence for documents (Milestone 1).

A simple, reliable storage strategy for a single-user local-development MVP:

- Each document is stored as ``<documents_dir>/<id>.pdf`` (the raw uploaded bytes).
- Metadata is stored as ``<documents_dir>/<id>.json``.
- ``<id>`` is a UUIDv4 generated by the service, so stored names are always safe (no path
  traversal) and unique.

All runtime data lives under ``documents_dir`` (default ``.data/documents``), which is git-ignored.
No external database is used.
"""

from __future__ import annotations

import json
import logging
from datetime import UTC, datetime
from pathlib import Path

from enterprise_ai_document_assistant.services.documents.models import (
    DocumentMetadata,
    DocumentStatus,
)

logger = logging.getLogger(__name__)


class DocumentNotFoundError(Exception):
    """Raised when a document id does not exist in storage."""


class DocumentStore:
    """Filesystem-backed store for documents and their metadata."""

    def __init__(self, root: str | Path) -> None:
        self._root = Path(root)
        self._root.mkdir(parents=True, exist_ok=True)

    @property
    def root(self) -> Path:
        return self._root

    def _pdf_path(self, document_id: str) -> Path:
        return self._root / f"{document_id}.pdf"

    def _meta_path(self, document_id: str) -> Path:
        return self._root / f"{document_id}.json"

    def save(self, document_id: str, data: bytes, metadata: DocumentMetadata) -> None:
        """Persist the raw PDF bytes and the metadata for a document."""
        self._pdf_path(document_id).write_bytes(data)
        self._meta_path(document_id).write_text(
            metadata.model_dump_json(indent=2), encoding="utf-8"
        )
        logger.info("Stored document %s (%d bytes)", document_id, len(data))

    def get(self, document_id: str) -> DocumentMetadata:
        """Return the metadata for a document, or raise :class:`DocumentNotFoundError`."""
        meta_path = self._meta_path(document_id)
        if not meta_path.exists():
            raise DocumentNotFoundError(f"Document '{document_id}' was not found.")
        return DocumentMetadata.model_validate_json(meta_path.read_text(encoding="utf-8"))

    def list(self) -> list[DocumentMetadata]:
        """Return all documents, most recent first."""
        docs: list[DocumentMetadata] = []
        for meta_path in self._root.glob("*.json"):
            try:
                docs.append(
                    DocumentMetadata.model_validate_json(meta_path.read_text(encoding="utf-8"))
                )
            except (json.JSONDecodeError, ValueError) as exc:
                # A corrupt metadata file should not break listing; log and skip it.
                logger.warning("Skipping unreadable metadata file %s: %s", meta_path.name, exc)
        docs.sort(key=lambda d: d.created_at, reverse=True)
        return docs

    def delete(self, document_id: str) -> None:
        """Remove a document's PDF and metadata (best-effort)."""
        for path in (self._pdf_path(document_id), self._meta_path(document_id)):
            if path.exists():
                path.unlink()
        logger.info("Deleted document %s", document_id)


def utc_now() -> datetime:
    """Return the current UTC time (timezone-aware)."""
    return datetime.now(UTC)


def build_metadata(
    document_id: str,
    filename: str,
    status: DocumentStatus,
    page_count: int | None,
    error: str | None = None,
) -> DocumentMetadata:
    """Construct a :class:`DocumentMetadata` with a fresh UTC timestamp."""
    return DocumentMetadata(
        id=document_id,
        filename=filename,
        status=status,
        page_count=page_count,
        created_at=utc_now(),
        error=error,
    )
